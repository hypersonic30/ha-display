#!/usr/bin/env python3
"""Generate LVGL 8 fonts (Latin-1 + Euro, 4 bpp, uncompressed) from a TTF.

Needs Pillow with FreeType. Output: src/fonts/ui_font_<size>.c (committed, so
this tool is only needed to change sizes or ranges).

  python3 tools/gen_fonts.py .pio/libdeps/esp32/lvgl/scripts/built_in_font/Montserrat-Medium.ttf
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

SIZES = (12, 14, 16, 20, 24)
RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x20AC, 0x20AC)]  # Latin-1 + Euro


def render(font, ch):
    adv = round(font.getlength(ch) * 16)
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return adv, 0, 0, 0, 0, b""
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    ink = img.getbbox()  # PIL pads the box up to the baseline; keep only the ink
    if ink is None:
        return adv, 0, 0, 0, 0, b""
    img = img.crop(ink)
    x0, y1, w, h = x0 + ink[0], y0 + ink[3], img.width, img.height
    px = [(v * 15 + 127) // 255 for v in img.tobytes()]
    if len(px) % 2:
        px.append(0)
    data = bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
    return adv, w, h, x0, -y1, data


def gen(ttf, size):
    font = ImageFont.truetype(ttf, size, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    bitmap, dscs, cmaps = bytearray(), [], []
    gid = 1
    for lo, hi in RANGES:
        cmaps.append((lo, hi - lo + 1, gid))
        for cp in range(lo, hi + 1):
            adv, w, h, ox, oy, data = render(font, chr(cp))
            dscs.append((len(bitmap) if data else 0, adv, w, h, ox, oy))
            bitmap += data
            gid += 1
    out = [f"/* generated by tools/gen_fonts.py: {Path(ttf).name} {size}px, 4bpp */",
           '#include "fonts.h"', "",
           "static const uint8_t glyph_bitmap[] = {"]
    for i in range(0, len(bitmap), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) + ",")
    out += ["};", "", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {",
            "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},"]
    for bi, adv, w, h, ox, oy in dscs:
        out.append(f"    {{.bitmap_index = {bi}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
                   f".ofs_x = {ox}, .ofs_y = {oy}}},")
    out += ["};", "", "static const lv_font_fmt_txt_cmap_t cmaps[] = {"]
    for start, length, g in cmaps:
        out.append(f"    {{.range_start = {start}, .range_length = {length}, .glyph_id_start = {g}, "
                   ".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                   ".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
    out += ["};", "", "static lv_font_fmt_txt_glyph_cache_t cache;", "",
            "static lv_font_fmt_txt_dsc_t font_dsc = {",
            "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,",
            "    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = %d, .bpp = 4," % len(cmaps),
            "    .kern_classes = 0, .bitmap_format = 0, .cache = &cache};", "",
            f"const lv_font_t ui_font_{size} = {{",
            "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
            "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
            f"    .line_height = {ascent + descent}, .base_line = {descent},",
            "    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -1, .underline_thickness = 1,",
            "    .dsc = &font_dsc};", ""]
    return "\n".join(out), len(bitmap)


def main():
    ttf = sys.argv[1]
    dest = Path(__file__).resolve().parent.parent / "src" / "fonts"
    dest.mkdir(parents=True, exist_ok=True)
    for size in SIZES:
        text, n = gen(ttf, size)
        (dest / f"ui_font_{size}.c").write_text(text)
        print(f"ui_font_{size}.c: {n} bitmap bytes")


if __name__ == "__main__":
    main()
